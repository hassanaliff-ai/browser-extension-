def test_new_threat_reactivates_released_block_and_rejects_stale_release(system):
    client, _, headers, _ = system
    h=headers['hasan']; first=submit(client)['containment'];investigate(client,h,first)
    body={'confirmed':True,'expected_revision':first['revision'],'reason':'Investigation supports explicit release'}
    path='/api/threat-blocks/'+first['id']+'/release'
    assert client.post(path,headers=h,json=body).status_code==200
    second=submit(client)['containment']
    assert second['active'] and second['id']==first['id'] and second['revision']>first['revision']
    assert second['case_id']!=first['case_id']
    assert client.post(path,headers=h,json=body).status_code==409


