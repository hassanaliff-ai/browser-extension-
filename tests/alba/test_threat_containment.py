def submit(client, code='malicious_url', state='detected', kind='url', target='https://danger.example/private?secret=PRIVATE'):
    response = client.post('/api/scans', headers=INGEST, json={'device_id':'containment-test', 'device_name':'Containment test device',
        'target_kind':kind, 'target':target, 'signals':[{'code':code,'status':state}]})
    assert response.status_code == 201, response.text
    return response.json()


def investigate(client, headers, block):
    case = client.get('/api/cases/'+block['case_id'], headers=headers).json()
    for status in ['investigating','resolved']:
        response=client.post('/api/cases/'+case['id']+'/status', headers=headers,
            json={'status':status,'assignee':case['assignee'],'expected_revision':case['revision'],'reason':'Verified containment evidence and completed investigation'})
        assert response.status_code == 200, response.text
        case=response.json()
    return case


def test_high_result_creates_atomic_block_and_incident(system):
    client, app, headers, _ = system
    result=submit(client)
    assert result['severity']=='Critical'
    block=result['containment']
    assert block['active'] and block['case_id']
    with app.state.session_factory() as db:
        row=db.get(ThreatBlock,block['id'])
        assert row.scan_id==result['id']
        assert 'PRIVATE' not in row.target_display
    case=client.get('/api/cases/'+block['case_id'],headers=headers['hasan']).json()
    assert case['device_name']=='Containment test device'
    assert case['timeline'][0]['action']=='created'
    assert case['containment']['active']


def test_existing_permanent_whitelist_cannot_bypass_high_risk(system):
    client, _, headers, _ = system
    h=headers['hasan']; target='https://danger.example/approved'
    req=client.post('/api/access/requests',headers=h,json={'target':target,'reason':'Expected business destination for test'}).json()
    approved=client.post('/api/access/requests/'+req['id']+'/review',headers=h,json={'confirmed':True,'decision':'whitelist','whitelist_forever':True,'expected_revision':req['revision'],'reason':'Head reviewed own destination and business purpose'})
    assert approved.status_code==200, approved.text
    submit(client)
    check=client.post('/api/access/check',headers=h,json={'target':target})
    assert check.json()['threat_blocked'] and not check.json()['allowed']
    assert client.post('/api/access/consume',headers=h,json={'target':target}).status_code==403
    assert client.post('/api/access/requests',headers=h,json={'target':target,'reason':'Request cannot bypass active threat'}).status_code==403


def test_hostname_block_covers_protocol_port_and_other_paths(system):
    client, _, headers, _ = system
    submit(client)
    for target in ['http://danger.example/other','https://danger.example:8443/other','https://DANGER.example./']:
        assert client.post('/api/access/check',headers=headers['hasan'],json={'target':target}).json()['threat_blocked']
    assert not client.post('/api/access/check',headers=headers['hasan'],json={'target':'https://danger.example.evil/'}).json().get('threat_blocked')


def test_release_requires_confirmation_and_resolved_latest_case(system):
    client, _, headers, _ = system
    block=submit(client)['containment']; path='/api/threat-blocks/'+block['id']+'/release'
    body={'confirmed':False,'expected_revision':block['revision'],'reason':'Reviewed source evidence and release rationale'}
    assert client.post(path,headers=headers['hasan'],json=body).status_code==422
    body['confirmed']=True
    assert client.post(path,headers=headers['hasan'],json=body).status_code==409
    investigate(client,headers['hasan'],block)
    response=client.post(path,headers=headers['hasan'],json=body)
    assert response.status_code==200, response.text
    assert not response.json()['active']


